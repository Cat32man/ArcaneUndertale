CELL_W, CELL_H, COLS = 6, 9, 16
FIRST, LAST = 32, 127

rows = (LAST - FIRST + 1 + COLS - 1) // COLS
img = Image.new("RGBA", (COLS * CELL_W, rows * CELL_H), (0, 0, 0, 0))
px = img.load()
missing = []
for code in range(FIRST, LAST + 1):
    ch = chr(code)
    if ch == " ":
        continue
    art = G.get(ch)
    if art is None:
        art = G["?"]
        missing.append(ch)
    idx = code - FIRST
    ox, oy = (idx % COLS) * CELL_W, (idx // COLS) * CELL_H
    for y, row in enumerate(art):
        assert y < CELL_H, ch
        assert len(row) == 5, (ch, y, row)
        for x, c in enumerate(row):
            if c == "#":
                px[ox + x, oy + y] = (255, 255, 255, 255)

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "font")
os.makedirs(out, exist_ok=True)
path = os.path.join(out, "pixel_font.png")
img.save(path)
print("wrote", os.path.normpath(path), img.size, "| glyphs falling back to '?':", "".join(missing) or "none")
