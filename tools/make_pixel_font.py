"""Generates assets/font/pixel_font.png - an original 5x7 pixel font (no external assets).

Edit a glyph below and re-run:   python tools/make_pixel_font.py

Each glyph is up to 9 rows of 5 columns ('#' = pixel). Rows 0-6 are the normal 7-row
body (the baseline sits under row 6); rows 7-8 are for descenders (g j p q y , ; _).
Atlas layout: 16 glyphs per row, ASCII 32..127, cell = 6x9 (5 wide + 1 spacing column).
"""
